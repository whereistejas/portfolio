//! Renders the blog posts, replacing Astro's `import.meta.glob` over `pages/posts/*.md`
//! and its markdown integration.
//!
//! Bodies are written to `generated/posts/<slug>.html` and included into the Rust table
//! alongside the listing metadata, so a post renders without a request of its own. They
//! are build intermediates, not served assets.

use std::error::Error;
use std::fs;
use std::path::{Path, PathBuf};

use crate::markdown;

pub fn generate(output_dir: &Path, out_dir: &Path) -> Result<(), Box<dyn Error>> {
    let posts_dir = output_dir.join("posts");
    fs::create_dir_all(&posts_dir)?;

    let mut sources = fs::read_dir(SOURCE)?
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| path.extension().is_some_and(|extension| extension == "md"))
        .collect::<Vec<_>>();
    sources.sort();

    let mut posts = Vec::with_capacity(sources.len());
    for source in &sources {
        let slug = source
            .file_stem()
            .and_then(|stem| stem.to_str())
            .ok_or("post file name is not valid UTF-8")?
            .to_owned();

        let mut post = Post::read(&slug, &fs::read_to_string(source)?)?;
        let rendered = posts_dir.join(format!("{slug}.html"));
        fs::write(&rendered, &post.body)?;
        post.rendered = fs::canonicalize(&rendered)?;
        posts.push(post);
    }

    // Newest first, as the Astro page sorted by frontmatter date descending.
    posts.sort_by(|a, b| b.date.cmp(&a.date));

    let table = posts.iter().map(Post::entry).collect::<Vec<_>>().join("\n");
    fs::write(
        out_dir.join("posts.rs"),
        format!(
            "/// Blog posts, generated by `build.rs` from `content/posts/*.md`.\n\
             pub const POSTS: &[Post] = &[\n{table}\n];\n"
        ),
    )?;

    // Consumed by `scripts/emit-routes.sh`, which needs a directory per post.
    let slugs = posts
        .iter()
        .map(|post| post.slug.as_str())
        .collect::<Vec<_>>();
    fs::write(output_dir.join("post-slugs.txt"), slugs.join("\n"))?;

    Ok(())
}

struct Post {
    slug: String,
    title: String,
    date: String,
    summary: String,
    body: String,
    /// Absolute path of the written HTML, so the table can `include_str!` it.
    rendered: PathBuf,
}

impl Post {
    fn read(slug: &str, source: &str) -> Result<Self, Box<dyn Error>> {
        let (frontmatter, markdown) = split_frontmatter(source)?;

        let title = field(frontmatter, "title").unwrap_or_else(|| slug.to_owned());
        let date = field(frontmatter, "date").ok_or("post is missing a date")?;

        // Fall back to the first prose block, as `firstParagraph` in blog.astro did.
        let summary = match field(frontmatter, "description") {
            Some(description) => description,
            None => markdown::to_plain_text(first_paragraph(markdown)),
        };

        Ok(Self {
            slug: slug.to_owned(),
            title,
            date,
            summary,
            body: markdown::to_html(markdown),
            rendered: PathBuf::new(),
        })
    }

    fn entry(&self) -> String {
        // The body is included rather than inlined so the generated file stays small
        // and the HTML has a single on-disk source.
        format!(
            "    Post {{ slug: {}, title: {}, date: {}, summary: {}, \
             body: include_str!({}) }},",
            quote(&self.slug),
            quote(&self.title),
            quote(&display_date(&self.date)),
            quote(&self.summary),
            quote(&self.rendered.display().to_string()),
        )
    }
}

/// Splits the leading `---` delimited YAML block from the body.
fn split_frontmatter(source: &str) -> Result<(&str, &str), Box<dyn Error>> {
    let rest = source
        .strip_prefix("---")
        .ok_or("post does not start with frontmatter")?;
    let end = rest
        .find("\n---")
        .ok_or("post frontmatter is unterminated")?;

    let body = rest[end..]
        .trim_start_matches('\n')
        .trim_start_matches("---")
        .trim_start_matches('\n');

    Ok((&rest[..end], body))
}

/// Reads one `key: value` line. The frontmatter here is flat, so a YAML parser would be a
/// dependency spent on nothing.
fn field(frontmatter: &str, key: &str) -> Option<String> {
    frontmatter
        .lines()
        .filter_map(|line| line.split_once(':'))
        .find(|(name, _)| name.trim() == key)
        .map(|(_, value)| value.trim().trim_matches('"').trim_matches('\'').to_owned())
}

fn first_paragraph(markdown: &str) -> &str {
    markdown
        .split("\n\n")
        .map(str::trim)
        .find(|block| !block.is_empty() && !block.starts_with('#'))
        .unwrap_or_default()
}

/// Formats `2026-03-22` as `22 Mar 2026`, matching the `en-GB` output of
/// `toLocaleDateString` in blog.astro.
fn display_date(date: &str) -> String {
    let parts = date.split('-').collect::<Vec<_>>();
    let [year, month, day] = parts.as_slice() else {
        return date.to_owned();
    };

    let month = month
        .parse::<usize>()
        .ok()
        .and_then(|month| MONTHS.get(month.wrapping_sub(1)))
        .copied()
        .unwrap_or(*month);

    format!("{day} {month} {year}")
}

fn quote(value: &str) -> String {
    format!("{value:?}")
}

const SOURCE: &str = "content/posts";
/// Month abbreviations as en-GB renders them. Note **"Sept"**: current CLDR abbreviates
/// September with four letters in en-GB, and the reading lists use the same
/// spelling, so the two date formats on the site agree. Kept in step with `readwise/src/main.rs`.
const MONTHS: [&str; 12] = [
    "Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sept", "Oct", "Nov", "Dec",
];
